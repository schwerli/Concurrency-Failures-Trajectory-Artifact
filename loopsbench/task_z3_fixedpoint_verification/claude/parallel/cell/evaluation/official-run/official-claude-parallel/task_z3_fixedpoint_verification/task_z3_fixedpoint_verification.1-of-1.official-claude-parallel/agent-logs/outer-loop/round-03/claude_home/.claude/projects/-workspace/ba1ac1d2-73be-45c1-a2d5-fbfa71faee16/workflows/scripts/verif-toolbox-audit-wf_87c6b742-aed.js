phase('Audit')
log('auditing ' + AUDITORS.length + ' dimensions of the verification toolbox')

const perDimension = await pipeline(
  AUDITORS,
  a => agent(a.prompt, { label: 'audit:' + a.key, phase: 'Audit', schema: FINDINGS_SCHEMA }),
  (res, a) => {
    const findings = (res && res.findings) || []
    if (!findings.length) return []
    return parallel(findings.map(f => () =>
      agent(COMMON + [
        'You are an adversarial VERIFIER. Another agent claims the following defect in the',
        'verification toolbox at ' + REPO + '. Your default assumption is that it is WRONG.',
        '',
        'CLAIM: ' + f.title,
        'FILE: ' + f.file + (f.line ? ':' + f.line : ''),
        'SEVERITY CLAIMED: ' + f.severity,
        'REQUIREMENT CLAUSE CLAIMED VIOLATED: ' + f.requirement_clause,
        'DETAIL: ' + f.detail,
        'CLAIMED REPRO: ' + f.repro,
        '',
        'Do this:',
        '1. Read the cited code yourself.',
        '2. Read the cited requirement clause in ' + REPO + '/requirements/ and quote it. If the',
        '   claim misreads the requirement, that alone makes it not-a-bug.',
        '3. ACTUALLY RUN the repro (adapt it if it is sloppy, but do not weaken it). Paste what it',
        '   printed.',
        '4. Decide: real=true ONLY if you reproduced the defect or can prove it rigorously.',
        '   If the claimed repro does not reproduce, real=false.',
        '5. If real, give the minimal concrete fix.',
        '',
        'Be skeptical. "The code could be clearer" is not-a-bug. "A named API the requirement',
        'spells out is genuinely absent" IS a bug. Set real=false if uncertain.',
      ].join('\n'),
        { label: 'verify:' + a.key + ':' + f.title.slice(0, 40), phase: 'Verify', schema: VERDICT_SCHEMA })
        .then(v => ({ dimension: a.key, finding: f, verdict: v }))
    ))
  }
)

const all = perDimension.flat().filter(Boolean)
const confirmed = all.filter(x => x.verdict && x.verdict.real && x.verdict.corrected_severity !== 'not-a-bug')

log(all.length + ' candidate findings, ' + confirmed.length + ' survived adversarial verification')

return {
  totalCandidates: all.length,
  confirmed: confirmed.map(x => ({
    dimension: x.dimension,
    title: x.finding.title,
    file: x.finding.file,
    line: x.finding.line,
    severity: x.verdict.corrected_severity,
    requirement_clause: x.finding.requirement_clause,
    detail: x.finding.detail,
    evidence: x.verdict.evidence,
    fix: x.verdict.fix,
  })),
  refuted: all.filter(x => confirmed.indexOf(x) === -1).map(x => ({
    dimension: x.dimension,
    title: x.finding.title,
    why: x.verdict ? x.verdict.evidence : 'verifier failed',
  })),
}
